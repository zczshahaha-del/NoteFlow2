import assert from "node:assert/strict";
import { buildOutlineModel, headingBeforeOffset, outlineAncestors, visibleOutlineNodes } from "../src/utils/outlineNavigation.ts";
const headings = Array.from({ length: 125 }, (_, i) => ({ id: `id-${i}`, level: i % 5 ? 3 : 2, text: `章节 ${i}`, hierarchyDepth: i % 5 ? 1 : 0 }));
const model = buildOutlineModel(headings);
assert.equal(model.roots.length, 25);
assert.equal(model.defaults.size, 25);
assert.equal(visibleOutlineNodes(model, model.defaults).length, 25);
const ancestors = outlineAncestors(model, "id-17");
assert.deepEqual(ancestors, [model.nodes.get("id-15")!.key]);
const opened = new Set(model.defaults); ancestors.forEach(key => opened.delete(key));
assert.equal(visibleOutlineNodes(model, opened).length, 29);
assert.equal(visibleOutlineNodes(model, new Set()).length, 125);
const shifted = buildOutlineModel(headings.map(h => ({ ...h, id: `shifted-${h.id}` })));
assert.deepEqual([...shifted.defaults], [...model.defaults], "Body position shifts preserve fold keys");
const duplicate = buildOutlineModel([{ id: "a", level: 2, text: "相同标题" }, { id: "b", level: 2, text: "相同标题" }]);
assert.notEqual(duplicate.nodes.get("a")!.key, duplicate.nodes.get("b")!.key);
const titleSpine = buildOutlineModel([{ id: "title", level: 1, hierarchyDepth: 0, text: "文档标题" }, ...headings.map(h => ({ ...h, hierarchyDepth: h.hierarchyDepth + 1 }))]);
assert(!titleSpine.defaults.has(titleSpine.nodes.get("title")!.key));
assert.equal(visibleOutlineNodes(titleSpine, titleSpine.defaults).length, 26);
assert.equal(buildOutlineModel(headings.slice(0, 100)).defaults.size, 0, "Short notes keep every heading visible");
assert.equal(buildOutlineModel(headings.map(h => ({ ...h, level: 2, hierarchyDepth: 0 }))).expandable.size, 0, "Flat documents do not invent semantic groups");
assert.equal(headingBeforeOffset([], 10), "");
const offsets = [{ id: "first", offset: 100 }, { id: "second", offset: 300 }, { id: "third", offset: 900 }];
for (const [offset, expected] of [[0, "first"], [100, "first"], [299, "first"], [300, "second"], [500, "second"], [900, "third"], [10000, "third"]] as const) assert.equal(headingBeforeOffset(offsets, offset), expected);
console.log(JSON.stringify({ ok: true, assertions: 20, grouping: true, positionShiftKeys: true, offsetSearch: true }));
