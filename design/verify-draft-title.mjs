import assert from 'node:assert/strict';
import { mkdtemp, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = path.dirname(fileURLToPath(import.meta.url));
const renderer = process.env.NOTEFLOW_VISUALIZE_RENDERER;
const playwrightPath = process.env.NOTEFLOW_PLAYWRIGHT_MODULE;
assert(renderer && playwrightPath, 'Set NOTEFLOW_VISUALIZE_RENDERER and NOTEFLOW_PLAYWRIGHT_MODULE');
const output = await mkdtemp(path.join(tmpdir(), 'noteflow-draft-title-'));
const html = path.join(output, 'review.html');
const source = await readFile(path.join(root, 'noteflow-draft-title.source.html'), 'utf8');
assert(!source.includes('fetch('));
assert(!source.includes('\\n'));
const built = spawnSync('python3', [renderer, path.join(root, 'noteflow-draft-title.source.html'), html], {encoding:'utf8'});
assert.equal(built.status, 0, built.stderr);
const { chromium } = await import(pathToFileURL(playwrightPath));
const browser = await chromium.launch({headless:true, executablePath:process.env.NOTEFLOW_BROWSER_EXECUTABLE});
const checks = [];
try {
  for (const width of [736, 320]) {
    const context = await browser.newContext({viewport:{width,height:1200}, colorScheme:'light',hasTouch:width===320});
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.route('http://**', route => route.abort());
    await page.route('https://**', route => route.abort());
    await page.goto(pathToFileURL(html).href);
    const frame = page.frameLocator('iframe');
    const quiet = frame.locator('[data-editor="quiet"]');
    const input = quiet.getByRole('textbox', {name:'草稿标题'});
    const title = quiet.getByRole('button', {name:'编辑草稿标题'});
    const generate = quiet.locator('.nfdt-generate');
    await title.waitFor({state:'visible'});
    const fits = () => quiet.evaluate(el => ({width:el.clientWidth,scroll:el.scrollWidth,cardWidth:el.querySelector('.nfdt-card').getBoundingClientRect().width}));
    assert((await fits()).scroll <= (await fits()).width, 'initial overflow');
    await page.screenshot({path:path.join(output,`initial-${width}.png`),fullPage:true});
    await title.click();
    await input.fill('《两小儿辩日》教学设计');
    await input.press('Escape');
    assert.equal(await quiet.locator('.nfdt-title-text').textContent(), '《两小儿辩日》教案');
    await title.click();
    await input.fill('  ');
    await quiet.getByRole('button', {name:'完成',exact:true}).click();
    assert(await quiet.getByRole('alert').isVisible());
    await input.fill('《两小儿辩日》教学设计');
    await page.screenshot({path:path.join(output,`editing-${width}.png`),fullPage:true});
    await input.press('Enter');
    assert.equal(await quiet.locator('.nfdt-title-text').textContent(), '《两小儿辩日》教学设计');
    await generate.click();
    assert(await quiet.locator('.nfdt-outline').isVisible());
    assert.equal(await quiet.locator('.nfdt-outline-title').textContent(), '《两小儿辩日》教学设计');
    assert.equal(await quiet.locator('.nfdt-outline li').count(), 6);
    await page.screenshot({path:path.join(output,`outline-${width}.png`),fullPage:true});
    await title.click();
    await input.fill('《揠苗助长》教案');
    await input.press('Enter');
    assert(await quiet.locator('.nfdt-notice').isVisible());
    assert.equal(await quiet.locator('.nfdt-outline-title').textContent(), '《两小儿辩日》教学设计', 'title edit rewrote outline');
    assert.equal(await generate.textContent(), '按新标题重新生成');
    await page.screenshot({path:path.join(output,`changed-${width}.png`),fullPage:true});
    await generate.click();
    assert.equal(await quiet.locator('.nfdt-outline-title').textContent(), '《揠苗助长》教案');
    await generate.click();
    assert(!(await quiet.locator('.nfdt-outline').isVisible()));
    await generate.click();
    assert(await quiet.locator('.nfdt-outline').isVisible());
    await title.click();
    await input.fill('很长的教案标题'.repeat(15));
    await input.press('Enter');
    assert((await fits()).scroll <= (await fits()).width, 'long title overflow');
    await frame.locator('.viz-carousel-picker summary').click();
    await frame.locator('.viz-carousel-options').getByRole('button',{name:'直接输入',exact:true}).click();
    const direct = frame.locator('[data-editor="field"]');
    const directInput = direct.getByRole('textbox', {name:'草稿标题'});
    await directInput.waitFor({state:'visible'});
    await directInput.fill('《两小儿辩日》课堂教案');
    await direct.locator('.nfdt-generate').click();
    assert.equal(await direct.locator('.nfdt-outline-title').textContent(), '《两小儿辩日》课堂教案');
    await directInput.fill('临时输入');
    await directInput.press('Escape');
    assert.equal(await directInput.inputValue(), '《两小儿辩日》课堂教案');
    await direct.locator('.nfdt-header').click();
    const renderFrame = page.frames().find(f => f !== page.mainFrame());
    await renderFrame.evaluate(() => window.dispatchEvent(new CustomEvent('openai:set_globals',{detail:{globals:{widgetState:{privateContent:{version:'draft-title-preview-v1',revision:100,views:[{title:'恢复的标题',outlineTitle:'原大纲标题'},{title:'恢复的直接输入',outlineTitle:''}]}}}}})));
    assert.equal(await directInput.inputValue(), '恢复的直接输入');
    assert.equal(await quiet.locator('.nfdt-title-text').textContent(), '恢复的标题');
    assert.equal(await quiet.locator('.nfdt-outline-title').textContent(), '原大纲标题');
    await page.emulateMedia({colorScheme:'dark', reducedMotion:'reduce'});
    await renderFrame.evaluate(() => window.dispatchEvent(new CustomEvent('openai:set_globals',{detail:{globals:{widgetState:{privateContent:{version:'draft-title-preview-v1',revision:1,views:[{title:'旧回包',outlineTitle:''},{title:'旧回包',outlineTitle:''}]}}}}})));
    assert.equal(await directInput.inputValue(), '恢复的直接输入', 'stale host state overwrote title');
    await page.screenshot({path:path.join(output,`dark-${width}.png`),fullPage:true});
    const geometry = await direct.evaluate(el => {
      const card = el.querySelector('.nfdt-card').getBoundingClientRect();
      const button = el.querySelector('.nfdt-generate').getBoundingClientRect();
      return {fits:el.scrollWidth<=el.clientWidth,buttonFits:button.right<=card.right,buttonHeight:button.height};
    });
    assert(geometry.fits && geometry.buttonFits, 'direct input overflow');
    if(width===320) assert(geometry.buttonHeight>=44, 'touch target too small');
    assert.deepEqual(errors, []);
    checks.push({width,editCancel:true,emptyGuard:true,confirmedGeneration:true,outlinePreserved:true,regenerate:true,collapse:true,longTitle:true,bothVariants:true,restore:true,darkReducedMotion:true,pageErrors:errors});
    await context.close();
  }
} finally {await browser.close();}
console.log(JSON.stringify({output,checks,productCodeChanged:false,realNetwork:false},null,2));
